#include <chrono>
#include <cmath>
#include <cstdio>
#include <iostream>
#include <random>
#include "FFT.hpp"

using namespace std;

volatile double sink; // so the compiler can't throw the work away

// keep calling fft or dft on x until 200ms passed, return avg ms per call
// small n finishes in microseconds so one call alone is too noisy to time
double timer(const vector<cd>& x, bool useFft) {
    int runs = 0;
    double ms = 0;
    auto start = chrono::high_resolution_clock::now();
    while (ms < 200) {
        vector<cd> X = useFft ? fft(x) : dft(x);
        sink = X[0].real();
        runs++;
        ms = chrono::duration<double, milli>(chrono::high_resolution_clock::now() - start).count();
    }
    return ms / runs;
}

int main() {
    mt19937 gen(42);
    uniform_real_distribution<double> dist(-1, 1);

    int maxDft = 1 << 15; // ~9s per dft call here, bigger is not worth the wait
    int maxFft = 1 << 20;

    cout << "n\tdft(ms)\t\tfft(ms)\t\tspeedup" << endl;

    vector<int> ns;
    vector<double> dfts, ffts; // dft is nan once n > maxDft
    double lastDft = 0, lastFft = 0, lastFftAtDft = 0; // for the reference lines in the plot
    int lastDftN = 0;
    for (int n = 2; n <= maxFft; n *= 2) {
        vector<cd> x(n);
        for (auto& v : x) v = cd(dist(gen), dist(gen));

        double f = timer(x, true);
        double d = n <= maxDft ? timer(x, false) : NAN;
        if (n <= maxDft) { lastDft = d; lastDftN = n; lastFftAtDft = f; }
        lastFft = f;

        ns.push_back(n);
        dfts.push_back(d);
        ffts.push_back(f);
        cout << n << "\t" << d << "\t" << f << "\t" << d / f << endl;
    }

    // Everything from here down (reference lines + gnuplot) is generated by AI, since plotting in C++
    // is really tricky and I don't think the plotting syntax is related to the content of the course.

    // scale n^2 and nlogn so they go through the last measured point
    double a = lastDft / ((double)lastDftN * lastDftN);
    double b = lastFft / ((double)maxFft * log2(maxFft));
    double s = (lastDft / lastFftAtDft) / (lastDftN / log2(lastDftN)); // same idea for n/logn

    FILE* gp = popen("gnuplot", "w");
    // send the numbers straight to gnuplot as a datablock, no csv file needed
    fprintf(gp, "$data << EOD\n");
    for (int i = 0; i < ns.size(); i++)
        fprintf(gp, "%d,%g,%g,%g\n", ns[i], dfts[i], ffts[i], dfts[i] / ffts[i]);
    fprintf(gp, "EOD\n");
    fprintf(gp, "set terminal pngcairo size 900,600\n");
    fprintf(gp, "set datafile separator ','\n");
    fprintf(gp, "set logscale y 10\n");
    fprintf(gp, "set logscale x 2\n");
    fprintf(gp, "set format x '2^{%%L}'\n");
    fprintf(gp, "set format y '10^{%%L}'\n");
    fprintf(gp, "set xlabel 'n'\n");
    fprintf(gp, "set key left top\n");
    fprintf(gp, "set grid\n");

    fprintf(gp, "set output 'results.png'\n");
    fprintf(gp, "set title 'DFT vs FFT runtime'\n");
    fprintf(gp, "set ylabel 'avg ms per call'\n");
    fprintf(gp, "plot $data using 1:2 with linespoints lw 2 title 'DFT', "
                "$data using 1:3 with linespoints lw 2 title 'FFT', "
                "%g*x**2 dt 2 lc rgb 'gray30' title 'c n^2', "
                "%g*x*log(x)/log(2) dt 3 lc rgb 'gray30' title 'c n log n'\n", a, b);

    fprintf(gp, "set output 'speedup.png'\n");
    fprintf(gp, "set title 'how many times faster FFT is'\n");
    fprintf(gp, "set ylabel 'DFT time / FFT time'\n");
    fprintf(gp, "set xrange [2:%d]\n", lastDftN);
    fprintf(gp, "set format y '%%g'\n");
    fprintf(gp, "plot $data using 1:4 with linespoints lw 2 title 'measured', "
                "%g*x/(log(x)/log(2)) dt 2 lc rgb 'gray30' title 'c n / log n'\n", s);
    pclose(gp);
    cout << "plots -> results.png, speedup.png" << endl;
    return 0;
}
