// I wrote this code using AI to know how long would it take to run the full programme.
// redraws the bar every 0.2s until stop is set
void showProgress(string label, atomic<int>& done, int total, atomic<bool>& stop) {
    auto start = chrono::high_resolution_clock::now();
    while (true) {
        bool last = stop;
        int filled = 30 * done / total;
        int sec = chrono::duration<double>(chrono::high_resolution_clock::now() - start).count();
        cout << "\r" << label << "\t[" << string(filled, '#') << string(30 - filled, '.') << "] " << done << "/" << total << " " << sec << "s" << flush;
        if (last) break;
        this_thread::sleep_for(chrono::milliseconds(200));
    }
    cout << endl;
}

int main() {
    mt19937 gen(42);
    uniform_int_distribution<int> dist(0, 1000000);

    vector<int> sizes = {10, 100, 1000, 10000, 100000, 1000000};
    // small sizes are too fast to time, so run them way more
    map<int, int> trials = {{10, 1000}, {100, 1000}, {1000, 100}, {10000, 20}, {100000, 10}, {1000000, 5}};
    vector<pair<string, void (*)(vector<int>&)>> sorts = {
        {"insertion", insertionSort<int>}, {"merge", mergeSort<int>}, {"quick", quickSort<int>}, {"radix", radixSort}};
    map<string, map<int, double>> times; // average time (ms) per sort

    for (const auto& size : sizes) {
        // same inputs for every sort
        vector<vector<int>> inputs(trials[size]);
        for (auto& input : inputs)
            for (int i=0; i<size; i++) input.push_back(dist(gen));

        for (const auto& [name, sortFn] : sorts) {
            int t = inputs.size();
            // insertion has n^2 time complexity, reduce number of rounds to get the result faster
            if (name == "insertion" && size == 100000) t = 3;
            if (name == "insertion" && size == 1000000) t = 1;

            vector<vector<int>> arrs(inputs.begin(), inputs.begin() + t);

            // The following three lines are also generated by AI for showing the progress bar.
            atomic<int> done(0);
            atomic<bool> stop(false);
            thread bar(showProgress, name + " n=" + to_string(size), ref(done), t, ref(stop));

            auto start = chrono::high_resolution_clock::now();
            for (auto& arr : arrs) {
                sortFn(arr);
                done++;
            }
            auto end = chrono::high_resolution_clock::now();

            // Also progress bar.
            stop = true;
            bar.join();

            // calculate and save the average time for t times running the algorithm.
            times[name][size] = chrono::duration<double, milli>(end - start).count() / t;
        }
    }

    // dump to csv + print the same thing
    ofstream csv("results.csv");
    csv << "size,insertion,merge,quick,radix" << endl;
    cout << endl << "size,insertion,merge,quick,radix (avg ms)" << endl;
    for (auto size : sizes) {
        csv << size;
        cout << size;
        for (auto& [name, sortFn] : sorts) {
            csv << "," << times[name][size];
            cout << "," << times[name][size];
        }
        csv << endl;
        cout << endl;
    }
    csv.close();

    // pipe commands into gnuplot, log-log so every size fits
    // This piece of code is also generated by AI as plotting in C++ is very tricky
    // and I assume the plotting syntax in C++ isn't really related to the content of the course.
    FILE* gp = popen("gnuplot", "w");
    fprintf(gp, "set terminal pngcairo size 900,600\n");
    fprintf(gp, "set output 'results.png'\n");
    fprintf(gp, "set datafile separator ','\n");
    fprintf(gp, "set logscale xy\n");
    fprintf(gp, "set rmargin 6\n"); // last x label gets cut off otherwise
    fprintf(gp, "set title 'sort time on random ints'\n");
    fprintf(gp, "set xlabel 'n'\n");
    fprintf(gp, "set ylabel 'avg ms per sort'\n");
    fprintf(gp, "set key left top\n");
    fprintf(gp, "plot for [i=2:5] 'results.csv' using 1:i with linespoints title columnheader(i)\n");
    pclose(gp);
    cout << "plot -> results.png" << endl;
    return 0;
}
